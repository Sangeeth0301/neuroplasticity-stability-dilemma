"""Fairness figure, paired bootstrap, and the written results file.

    python scripts/report/finalize_results.py   ->  figures/analysis/FIN5_fairness.*, results/RESULTS_FINAL.md
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from qcs.eval.significance import paired_bootstrap

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "results"
FIN, FAIR, FIG = RES / "raw" / "final", RES / "raw" / "fairness", ROOT / "figures" / "analysis"
ARMS = ["multi", "linear", "mlp"]
LABEL = {"multi": "Quantum (multi-qubit)", "linear": "Linear", "mlp": "MLP"}
COLOR = {"multi": "#a3226a", "linear": "#0b5c73", "mlp": "#7a8791"}

F = {a: [json.load(open(f)) for f in sorted(FAIR.glob(f"{a}_s*.json"))] for a in ARMS}
fair = {}
for a, runs in F.items():
    b40 = np.array([r["best40"] for r in runs])
    b80 = np.array([r["best80"] for r in runs])
    fair[a] = {"best40": (b40.mean(), b40.std()), "best80": (b80.mean(), b80.std()),
               "per_seed_80": b80.tolist()}

fig, ax = plt.subplots(figsize=(8.5, 4.8))
w = 0.34
for i, a in enumerate(ARMS):
    for j, key in enumerate(("best40", "best80")):
        m, s = fair[a][key]
        ax.bar(i + (j - 0.5) * w, m, w, yerr=s, capsize=3, color=COLOR[a], alpha=1 if j else 0.6,
               edgecolor="white")
        ax.text(i + (j - 0.5) * w, m + 0.04, f"{m:.2f}", ha="center", fontsize=9)
ax.set_xticks(range(3), [LABEL[a] for a in ARMS])
ax.set(ylim=(0, 1.12), ylabel="reversal MRR at each model's BEST learning rate",
       title="Fairness check: learning the new rule with the best step size\n"
             "(light = 40 steps, dark = 80 steps; mean ± sd over 3 seeds)")
ax.grid(axis="y", alpha=0.25)
ax.spines[["top", "right"]].set_visible(False)
fig.savefig(FIG / "FIN5_fairness.png", dpi=150, bbox_inches="tight", facecolor="white")
fig.savefig(FIG / "FIN5_fairness.svg", bbox_inches="tight", facecolor="white")

# paired bootstrap over threads on the sealed test split (per-seed per-probe MRR averaged)
runs = {a: [json.load(open(f)) for f in sorted(FIN.glob(f"{a}_s*.json"))] for a in ARMS + ["quantum"]}


def per_thread(a):
    th = runs[a][0]["test_per_probe"].keys()
    return {t: np.mean([r["test_per_probe"][t] for r in runs[a]], axis=0).tolist() for t in th}


sig = {}
for x, y in [("multi", "linear"), ("multi", "mlp"), ("multi", "quantum"), ("linear", "mlp")]:
    sig[f"{x} - {y}"] = paired_bootstrap(per_thread(x), per_thread(y), seed=7)

summ = json.load(open(RES / "final_summary.json"))
LAB = {"multi": "Quantum, multi-qubit readout (new)", "quantum": "Quantum, single-qubit readout (original)",
       "linear": "Linear (parameter-matched)", "mlp": "MLP (65k params)"}


def pm(k, a):
    return f"{summ[a][k][0]:.3f} ± {summ[a][k][1]:.3f}"


L = ["# Final results — stability, plasticity and both together", "",
     "Setup: 120 sequential tasks, seeds 7/17/27, every arm at its own tuned learning rate. "
     "Generated by `scripts/experiments/final_eval.py`, `scripts/experiments/plasticity_fairness.py`, "
     "`scripts/figures/make_final_figures.py`, `scripts/report/finalize_results.py`.", "",
     "## Scorecard (mean ± sd over 3 seeds)", "",
     "| arm | params | test MRR (sealed) | test stale-above ↓ | STABILITY: old-task MRR | "
     "PLASTICITY: reversal MRR (own lr) | combined | BWT |", "|---|---|---|---|---|---|---|---|"]
for a in ["multi", "quantum", "linear", "mlp"]:
    L.append(f"| {LAB[a]} | {summ[a]['params']:,} | {pm('test_mrr', a)} | {pm('test_stale', a)} | "
             f"{pm('retention_end', a)} | {pm('reversal_end', a)} | {pm('combined_end', a)} | "
             f"{pm('bwt', a)} |")
L += ["", "Stability = MRR of the model on the first 30 tasks after all 120 are learned. Plasticity = MRR "
      "on held-out probes after 40 gradient steps on a REVERSED rule (the superseded fact becomes the "
      "correct answer). Combined = harmonic mean of the two.", "",
      "## Fairness check — best learning rate per arm", "",
      "| arm | reversal MRR @40 steps | reversal MRR @80 steps | per-seed @80 |", "|---|---|---|---|"]
for a in ARMS:
    L.append(f"| {LABEL[a]} | {fair[a]['best40'][0]:.3f} ± {fair[a]['best40'][1]:.3f} | "
             f"{fair[a]['best80'][0]:.3f} ± {fair[a]['best80'][1]:.3f} | "
             f"{', '.join(f'{v:.2f}' for v in fair[a]['per_seed_80'])} |")
L += ["", "## Paired bootstrap on the sealed test split (thread is the unit; 6 threads)", "",
      "| comparison (MRR) | difference | 95% CI | p | significant |", "|---|---|---|---|---|"]
for k, r in sig.items():
    L.append(f"| {k} | {r['difference']:+.4f} | [{r['ci_low']:+.4f}, {r['ci_high']:+.4f}] | "
             f"{r['p_value']:.3f} | {'yes' if r['significant'] else 'no'} |")
E = json.load(open(RES / "evidence_summary.json"))
L += ["", "## Direct evidence: learns new things, remembers old ones (3 seeds, sealed test split)", "",
      "| arm | probes WITHOUT an outdated fact: MRR | probes WITH an outdated fact: MRR | facts >400 turns ago MRR | "
      "mean MRR over ALL past tasks after 120 | unseen-task MRR (tasks 20+) |", "|---|---|---|---|---|---|"]
for a in ["multi", "quantum", "linear", "mlp"]:
    e = E[a]
    L.append(f"| {LAB[a]} | " + " | ".join(f"{e[k][0]:.3f} ± {e[k][1]:.3f}" for k in
             ("unchanged", "updated", "far", "all_past", "unseen")) + " |")
L += ["", "Reference points: a model that sees only the last 100 turns scores 0.97 / 0.97 / 0.00 / 0.00 on "
      "facts 0-50 / 50-200 / 200-400 / >400 turns old; memory + plain cosine similarity (no learning) scores "
      "0.89 on probes with an outdated fact and 0.88-0.93 across distances. Figures: EV1, EV2, EV3. An 'outdated-fact probe' is a probe with at least one replaced (superseded) fact among its 64 candidates: 115 of the 360 test probes, all from update (adversarial) threads.", "",
      "## What is and is not supported", "",
      "- SUPPORTED: replacing the single-qubit readout with a learned readout over all 10 qubits "
      "raises sealed-test MRR from about 0.86 to about 0.97 with the same circuit.",
      "- SUPPORTED: the multi-qubit quantum model matches the parameter-matched linear model on test "
      "MRR; it does not beat it, and the MLP is more accurate.",
      "- SUPPORTED: stability is good for every arm (old-task MRR 0.87–1.00); the quantum model "
      "shows slightly lower stability and a higher stale-fact error rate than the classical arms.",
      "- SUPPORTED WITH A CAVEAT: after 120 tasks the quantum model adapts to a reversed rule faster "
      "than the classical arms. At the training learning rate the gap is large (0.84 vs ~0.2); with each "
      "arm's best learning rate and more steps the classical arms partly recover, so the honest "
      "statement is 'faster and more reliable', not 'classical arms cannot learn'.",
      "- NOT SUPPORTED: Tr(F) as a plasticity measure — it is noisy and the MLP's did not collapse here.",
      "- NOT TESTED: horizons of 1,000+ tasks, real quantum hardware, a real LLM; only 6 test threads.",
      ""]
(RES / "RESULTS_FINAL.md").write_text("\n".join(L), encoding="utf-8")
print("\n".join(L))
