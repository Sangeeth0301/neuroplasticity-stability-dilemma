"""Two independent gradient paths, and the test that they agree.

`autodiff`        backprop through the statevector simulator. Exact, and ~2|θ| times
                  cheaper — this is what training uses.
`parameter_shift` ∂⟨O⟩/∂θ_k = ½[⟨O⟩(θ_k+π/2) − ⟨O⟩(θ_k−π/2)]. The only path that
                  transfers to hardware.

The agreement test is not a formality: it is the single check that proves the simulator,
the gate parameterisation and the readout are all mutually consistent. Nothing in Phase 4
proceeds until it passes at 1e-6.

Note the shift rule holds for gates generated by an operator with eigenvalues ±1/2. Our
V(θ) exponentiates a SUM of 15 Pauli terms that do not commute, so the two-term rule
applies per parameter only when the other 14 are held fixed AND the generator for that
parameter squares to the identity — which each σ_α⊗σ_β does. The test below verifies
this empirically rather than taking it on faith.
"""

from __future__ import annotations

import numpy as np
import torch


def autodiff_grad(model, x: np.ndarray, target_fn=None) -> np.ndarray:
    """d(mean output)/dθ by backprop, shape = θ.shape."""
    model.zero_grad(set_to_none=True)
    out = model(x)
    loss = out.mean() if target_fn is None else target_fn(out)
    loss.backward()
    return model.theta.grad.detach().cpu().numpy().copy()


@torch.no_grad()
def parameter_shift_grad(model, x: np.ndarray, indices=None, shift: float = np.pi / 2
                         ) -> dict[tuple[int, int, int], float]:
    """d(mean ⟨Z⟩)/dθ_k by the shift rule, for a subset of parameter indices."""
    if indices is None:
        L, G, P = model.theta.shape
        indices = [(0, 0, 0), (L // 2, G // 2, 7), (L - 1, G - 1, 14)]
    grads: dict[tuple[int, int, int], float] = {}
    base = model.theta.detach().clone()
    for idx in indices:
        plus, minus = base.clone(), base.clone()
        plus[idx] += shift
        minus[idx] -= shift
        _, z_p = model(x, theta=plus, return_expectation=True)
        _, z_m = model(x, theta=minus, return_expectation=True)
        grads[idx] = float(0.5 * (z_p.mean() - z_m.mean()))
    return grads


def autodiff_expectation_grad(model, x: np.ndarray) -> np.ndarray:
    """d(mean ⟨Z⟩)/dθ — the quantity the shift rule computes, for a like-for-like test."""
    model.zero_grad(set_to_none=True)
    _, z = model(x, return_expectation=True)
    z.mean().backward()
    return model.theta.grad.detach().cpu().numpy().copy()


def agreement(model, x: np.ndarray, indices=None) -> dict:
    """Max |autodiff − parameter-shift| over the sampled parameters."""
    ad = autodiff_expectation_grad(model, x)
    ps = parameter_shift_grad(model, x, indices)
    diffs = {idx: abs(float(ad[idx]) - v) for idx, v in ps.items()}
    return {
        "max_abs_diff": max(diffs.values()),
        "pairs": [(list(idx), float(ad[idx]), ps[idx]) for idx in ps],
    }


@torch.no_grad()
def gradient_variance(model_factory, x: np.ndarray, depths: list[int], n_samples: int,
                      rng: np.random.Generator, param_idx=(0, 0, 0),
                      observable: str = "local_z") -> dict[int, float]:
    """Var[∂⟨O⟩/∂θ_k] over random initialisations — the barren-plateau instrument.

    Uses the parameter-shift rule (no autograd graph), so it measures the physical
    gradient a device would see.
    """
    out: dict[int, float] = {}
    for d in depths:
        model = model_factory(d, observable)
        vals = []
        for _ in range(n_samples):
            theta = torch.tensor(
                rng.uniform(-np.pi, np.pi, tuple(model.theta.shape)), dtype=torch.float32)
            plus, minus = theta.clone(), theta.clone()
            plus[param_idx] += np.pi / 2
            minus[param_idx] -= np.pi / 2
            _, zp = model(x, theta=plus, return_expectation=True)
            _, zm = model(x, theta=minus, return_expectation=True)
            vals.append(float(0.5 * (zp.mean() - zm.mean())))
        out[d] = float(np.var(vals))
    return out
